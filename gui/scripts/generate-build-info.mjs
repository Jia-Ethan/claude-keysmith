// 生成构建信息模块：GUI 版本来自 package.json，源码/sidecar commit 来自 git。
// 不写死任何伪装的发布版本；拿不到 git 信息时提交记为 null（channel 降级为 development）。
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const guiDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoDir = resolve(guiDir, "..");

const packageJson = JSON.parse(readFileSync(join(guiDir, "package.json"), "utf8"));

function gitCommit() {
  try {
    const out = execFileSync("git", ["rev-parse", "HEAD"], {
      cwd: repoDir,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
    return /^[0-9a-f]{40}$/.test(out) ? out : null;
  } catch {
    return null;
  }
}

const commit = gitCommit();
const buildInfo = {
  guiVersion: packageJson.version,
  channel: "beta",
  // 工作树在 HEAD 之上可能有未提交改动；commit 只标注构建来源，不代表已发布 tag。
  sourceCommit: commit,
  sidecarCommit: commit, // sidecar 与 GUI 同源构建
  generatedAt: new Date().toISOString(),
};

const target = join(guiDir, "src", "lib", "build-info.generated.js");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// GENERATED by scripts/generate-build-info.mjs — do not edit.\n` +
    `export const generatedBuildInfo = ${JSON.stringify(buildInfo, null, 2)};\n`,
  "utf8",
);
console.log(`build-info: gui=${buildInfo.guiVersion} channel=${buildInfo.channel} commit=${commit ?? "unavailable"}`);
